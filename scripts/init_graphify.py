#!/usr/bin/env python3
"""
Initialize Graphify for Autognosia.

Run this once after wiki has content:
  python3 scripts/init_graphify.py

Prerequisites:
  uv tool install graphifyy
  graphify install
"""

import os
import subprocess
import sys
from pathlib import Path

AUTOGNOSIA_HOME_STR = os.environ.get("AUTOGNOSIA_HOME", str(Path.home() / ".autognosia"))
AUTOGNOSIA_HOME = Path(AUTOGNOSIA_HOME_STR)
ACTIVE_WIKI = AUTOGNOSIA_HOME / "active-wiki"
ORACLE_BRAIN = AUTOGNOSIA_HOME / "oracle" / "brain"
MAIN_GRAPH_OUT = AUTOGNOSIA_HOME / "graphify-main-out"
ORACLE_GRAPH_OUT = AUTOGNOSIA_HOME / "graphify-oracle-out"
CONFIG_FILE = AUTOGNOSIA_HOME / "graphify-config.env"

def ensure_directories():
    """Create all required directory structure. Cross-platform."""
    dirs = [
        ACTIVE_WIKI / "projects",
        ACTIVE_WIKI / ".meta",
        ORACLE_BRAIN.parent,  # oracle/
        ORACLE_BRAIN,
        AUTOGNOSIA_HOME / "oracle" / "raw" / "research",
        AUTOGNOSIA_HOME / "oracle" / "raw" / "documents",
        AUTOGNOSIA_HOME / "oracle" / "raw" / "articles",
        AUTOGNOSIA_HOME / "oracle" / "raw" / "transcripts",
        AUTOGNOSIA_HOME / "oracle" / "raw" / "conversations",
        AUTOGNOSIA_HOME / "oracle" / "raw" / "imports",
        AUTOGNOSIA_HOME / "oracle" / "raw" / "assets",
        AUTOGNOSIA_HOME / "backups",
        AUTOGNOSIA_HOME / "secrets",
        MAIN_GRAPH_OUT.parent,
        ORACLE_GRAPH_OUT.parent,
    ]
    created = []
    for d in dirs:
        if not d.exists():
            d.mkdir(parents=True, exist_ok=True)
            created.append(str(d))
    return created

